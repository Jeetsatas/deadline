export class ToolRegistry {
  private static tools: ToolDefinition[] = ALL_TOOLS;

  static getAllTools(): ToolDefinition[] {
    return this.tools;
  }

  static getToolById(id: string): ToolDefinition | undefined {
    return this.tools.find((t) => t.id === id);
  }

  static getToolsByCategory(category: ToolCategory | 'all'): ToolDefinition[] {
    if (category === 'all') return this.tools;
    return this.tools.filter((t) => t.category === category);
  }

  static searchTools(query: string, category: ToolCategory | 'all' = 'all'): ToolDefinition[] {
    const list = this.getToolsByCategory(category);
    if (!query || !query.trim()) return list;

    const q = query.toLowerCase().trim();
    return list.filter((t) => {
      const matchName = t.name.toLowerCase().includes(q);
      const matchTagline = t.tagline.toLowerCase().includes(q);
      const matchDesc = t.description.toLowerCase().includes(q);
      const matchKeywords = t.keywords.some((k) => k.toLowerCase().includes(q));
      return matchName || matchTagline || matchDesc || matchKeywords;
    });
  }

  static getPopularTools(): ToolDefinition[] {
    return this.tools.filter((t) => t.isPopular);
  }
}
